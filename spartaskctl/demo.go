const demoUsage = `usage: spartaskctl demo apply <file.json>   create the demo company or reset it to the file
       spartaskctl demo check <file.json>   validate the file, write nothing`

// runDemo hands a demo company specification to spartask-admin inside the api container. Values
// written as "env:NAME" (passwords, database connection) are read here, from the environment of
// spartaskctl or else from .env, so secrets never sit in the specification file.
//
// A missing variable that is only used as a user password is generated: `apply` writes it to .env
// (previous file kept as .env.bak) and later runs reuse it; `check` only says it will. Anything else
// (a database host or password) comes from outside and must be set by hand.
func runDemo(ctx context.Context, s stack, args []string) error {
	if len(args) != 2 || (args[0] != "apply" && args[0] != "check") {
		return errors.New(demoUsage)
	}
	action, file := args[0], args[1]
	env, err := loadInstalledEnv(s)
	if err != nil {
		return err
	}
	data, err := os.ReadFile(file)
	if err != nil {
		return err
	}
	resolved, generated, err := resolveDemoSecrets(data, func(name string) string {
		if v := os.Getenv(name); v != "" {
			return v
		}
		return env.Get(name)
	}, demoPassword)
	if err != nil {
		return err
	}
	if len(generated) > 0 {
		names := sortedKeys(generated)
		if action == "check" {
			fmt.Printf("apply will generate %s in .env (user passwords)\n", strings.Join(names, ", "))
		} else {
			if err := saveDemoPasswords(s, env, generated); err != nil {
				return err
			}
			fmt.Printf("Generated %s in .env. To see them: sudo grep ^%s= .env\n", strings.Join(names, ", "), names[0])
		}
	}
	err = s.composeStream(ctx, bytes.NewReader(resolved), os.Stdout,
		"exec", "-T", "api", "/app/bin/spartask-admin", "demo", action, "-f", "-")
	if err != nil && strings.Contains(err.Error(), "spartask-admin") && strings.Contains(strings.ToLower(err.Error()), "no such file") {
		return fmt.Errorf("this Spartask release has no spartask-admin; update to a release that includes it (%w)", err)
	}
	return err
}

// saveDemoPasswords appends the generated passwords to .env, keeping the previous file as .env.bak.
func saveDemoPasswords(s stack, env *envFile, generated map[string]string) error {
	previous, err := os.ReadFile(s.path(".env"))
	if err != nil {
		return fmt.Errorf("read .env: %w", err)
	}
	block := []string{"# Demo company user passwords (generated by spartaskctl demo apply)."}
	for _, name := range sortedKeys(generated) {
		block = append(block, name+"="+generated[name])
	}
	env.insertAfter("", block)
	if err := writeSecretFile(s.path(".env.bak"), previous); err != nil {
		return err
	}
	return env.Save(s.path(".env"))
}

// demoPassword returns 24 URL-safe random characters (144 bits), safe in .env without quoting.
func demoPassword() (string, error) {
	b := make([]byte, 18)
	if _, err := rand.Read(b); err != nil {
		return "", err
	}
	return base64.RawURLEncoding.EncodeToString(b), nil
}

// resolveDemoSecrets replaces every JSON string value "env:NAME" by lookup(NAME). A missing NAME
// whose every use is a user password (users[].password) gets a value from generate, returned in
// generated so the caller can store it; every other missing variable is reported at once. Numbers
// keep their exact text.
func resolveDemoSecrets(data []byte, lookup func(string) string, generate func() (string, error)) ([]byte, map[string]string, error) {
	dec := json.NewDecoder(bytes.NewReader(data))
	dec.UseNumber()
	var doc any
	if err := dec.Decode(&doc); err != nil {
		return nil, nil, fmt.Errorf("demo file is not valid JSON: %w", err)
	}
	if dec.More() {
		return nil, nil, errors.New("demo file holds more than one JSON value")
	}

	// First pass: which references are missing, and whether each is used only as a user password.
	type use struct{ onlyPassword bool }
	missing := map[string]*use{}
	visit(doc, atRoot, func(name string, userPassword bool) {
		if lookup(name) != "" {
			return
		}
		if u, ok := missing[name]; ok {
			u.onlyPassword = u.onlyPassword && userPassword
			return
		}
		missing[name] = &use{onlyPassword: userPassword}
	})
	var unset []string
	for name, u := range missing {
		if !u.onlyPassword {
			unset = append(unset, name)
		}
	}
	if len(unset) > 0 {
		sort.Strings(unset)
		return nil, nil, fmt.Errorf("set %s in .env or in the environment (e.g. sudo %s=... ./spartaskctl demo ...)", strings.Join(unset, ", "), unset[0])
	}
	generated := map[string]string{}
	for name := range missing {
		value, err := generate()
		if err != nil {
			return nil, nil, fmt.Errorf("generate %s: %w", name, err)
		}
		generated[name] = value
	}

	// Second pass: replace every reference.
	doc = replaceRefs(doc, func(name string) string {
		if v, ok := generated[name]; ok {
			return v
		}
		return lookup(name)
	})
	out, err := json.Marshal(doc)
	if err != nil {
		return nil, nil, err
	}
	return out, generated, nil
}

// Where a value sits in the demo file, for telling user passwords apart from other secrets.
const (
	atRoot  = "root"
	atUsers = "users" // the top-level users list
	atUser  = "user"  // one entry of it
)

// visit calls fn for every "env:NAME" string in v; userPassword is true for users[].password.
func visit(v any, at string, fn func(name string, userPassword bool)) {
	switch t := v.(type) {
	case map[string]any:
		for k, item := range t {
			if name, ok := envRef(item); ok {
				fn(name, at == atUser && k == "password")
				continue
			}
			child := ""
			if at == atRoot && k == "users" {
				child = atUsers
			}
			visit(item, child, fn)
		}
	case []any:
		for _, item := range t {
			if name, ok := envRef(item); ok {
				fn(name, false)
				continue
			}
			child := ""
			if at == atUsers {
				child = atUser
			}
			visit(item, child, fn)
		}
	}
}

func replaceRefs(v any, value func(string) string) any {
	switch t := v.(type) {
	case map[string]any:
		for k, item := range t {
			t[k] = replaceRefs(item, value)
		}
	case []any:
		for i, item := range t {
			t[i] = replaceRefs(item, value)
		}
	case string:
		if name, ok := envRef(t); ok {
			return value(name)
		}
	}
	return v
}

func envRef(v any) (string, bool) {
	s, ok := v.(string)
	if !ok {
		return "", false
	}
	name, ok := strings.CutPrefix(s, "env:")
	if !ok {
		return "", false
	}
	return strings.TrimSpace(name), true
}

func sortedKeys(m map[string]string) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
